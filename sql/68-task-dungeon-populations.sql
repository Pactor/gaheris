-- Nothing has these. Not db-public, not the OpenDAoC reference database, not
-- DOLSharp; every one of the 120 task dungeon regions holds zero mobs in all
-- of them, and the fan sites that documented real dungeons never covered
-- these because they were instanced and were switched off years ago. So this
-- is generated, and it is worth being plain about which parts are evidence
-- and which are judgement.
--
-- Evidence: the region-to-dungeon-to-level-band mapping is the core's own,
-- read out of the arrays in TaskDungeonMission.cs. The entrances are the real
-- ones from db-public. The creature templates are real rows from our own
-- npctemplate table, filtered to the level band the core assigns that dungeon.
--
-- Judgement: which creatures suit which dungeon, inferred from the dungeon's
-- own name -- a Gossamer Grotto is spiders, a Sundered Tomb is the restless
-- dead, a mine is what burrows. And the positions.
--
-- Positions are laid out along the heading the entrance faces, 300 to 1500
-- units in with a little sideways scatter, and the boss at 2000. That is a
-- guess at the shape of a corridor rather than knowledge of one: we have no
-- geometry for these maps, only the door. Some creatures will end up inside
-- rock, and a Clear mission cannot be finished if one of them does. Expect to
-- tune the distances after walking a few.
--
-- Deterministic: seeded per region, so regenerating gives the same dungeon.

